  /**
   * @param {() => string} getLanguage Read on every call: the language can
   *        change while the page is open.
   * @returns {(key: string, vars?: Record<string, string | number>) => string}
   */
  function createTranslator(getLanguage) {
    return function t(key, vars) {
      const lang = getLanguage() === 'ar' ? 'ar' : 'en';
      const text = (CATALOG[lang] && CATALOG[lang][key]) || CATALOG.en[key] || key;
      if (!vars) return text;
      return text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
    };
  }

  const api = { CATALOG, createTranslator };

